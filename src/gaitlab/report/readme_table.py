"""Render the README results block from results/*.json (EVALUATION.md §5). No hard-coded values."""

from __future__ import annotations

import re
from pathlib import Path
from typing import Any

from gaitlab.report.results import load_reportable

START = "<!-- RESULTS:START -->"
END = "<!-- RESULTS:END -->"

# (area, name) → (row label, list of (metric path, display label)).
# Paths index into the "metrics" dict with dots. Values are read, never typed here.
HEADLINES: dict[tuple[str, str], tuple[str, list[tuple[str, str]]]] = {
    ("validation", "biocv_events"): (
        "Contact timing vs force plates (BioCV)",
        [("ic_error_ms.median", "IC error median, ms"), ("ic_within_1_frame", "IC within 1 frame")],
    ),
    ("validation", "own_cadence"): ("Cadence vs hand counts", [("mae_spm", "MAE, steps/min")]),
    ("grader", "ladder"): ("Grader agreement (test sessions)", [("best.qwk", "QWK (best model)")]),
    ("grader", "intra_rater"): ("My own re-grade (ceiling)", [("qwk", "QWK")]),
    ("grader", "verifier"): ("Cues grounded in measured features", [("pass_rate", "pass rate")]),
    ("bench", "trt"): ("TensorRT scoring pass", [("speedup_b1", "speedup, batch 1")]),
}


def _get(d: dict[str, Any], path: str) -> Any:
    cur: Any = d
    for part in path.split("."):
        if not isinstance(cur, dict) or part not in cur:
            return None
        cur = cur[part]
    return cur


def _fmt(v: Any) -> str:
    if isinstance(v, float):
        return f"{v:.3g}"
    return str(v)


def render(results: list[dict[str, Any]]) -> str:
    by_key = {(r["area"], r["name"]): r for r in results}
    rows = []
    for key, (label, metrics) in HEADLINES.items():
        r = by_key.get(key)
        if r is None:
            continue
        cells = []
        for path, mlabel in metrics:
            v = _get(r["metrics"], path)
            if v is not None:
                cells.append(f"{mlabel}: {_fmt(v)}")
        if cells:
            sha = (r.get("git_sha") or "")[:7]
            src = f"[{r['_path']}]({r['_path']}) @ `{sha}`"
            rows.append(f"| {label} | {'; '.join(cells)} | {src} |")
    if not rows:
        return "_No results yet. Generated by `gaitlab report` from `results/*.json`._"
    head = "| Measure | Value | Source |\n|---|---|---|"
    return head + "\n" + "\n".join(rows)


def update_readme(readme: str | Path = "README.md", root: str | Path = "results") -> bool:
    """Rewrite only the block between the RESULTS markers. Returns True if the file changed."""
    p = Path(readme)
    text = p.read_text()
    pattern = re.compile(re.escape(START) + r".*?" + re.escape(END), re.S)
    if not pattern.search(text):
        raise ValueError("README is missing RESULTS markers")
    new_block = f"{START}\n{render(load_reportable(root))}\n{END}"
    new_text = pattern.sub(lambda _m: new_block, text)
    if new_text != text:
        p.write_text(new_text)
        return True
    return False
